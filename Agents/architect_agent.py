import asyncio
from functools import lru_cache
from dotenv import load_dotenv

from output_store import save_text, read_project_file
from llm import get_llm

load_dotenv()

MAX_PRD_CHARS = 20_000

ARCHITECT_SYSTEM_PROMPT = """
You are a senior software architect. Given a Product Requirements Document (PRD), produce a System Design Document (SDD) in Markdown.

Use this exact structure:

# System Design Document

## 1. Overview
2-4 sentences. What's being built, architectural style, main components.

## 2. Technology Stack
Table: Category | Technology | Why
Include only relevant categories (Frontend, Backend, Database, Auth, Hosting, etc.).

## 3. File & Folder Structure
Text tree showing the recommended project layout. Include real filenames.

## 4. Data Model
For each entity: name, purpose, fields with types, relationships.

## 5. API Endpoints
For each endpoint:
- Method + path (e.g., POST /api/v1/tasks)
- Purpose
- Request body
- Response body
- Status codes
- Auth required (yes/no)

## 6. Core User Flows
For the 2-3 most important flows, describe the sequence of operations (client → API → DB → response).

## 7. Authentication & Authorization
How users authenticate and how access is controlled. Justify the choice.

## 8. External Dependencies
Third-party services and why they're needed.

## 9. Architectural Decisions
3-5 key decisions with brief justifications.

## 10. Out of Scope
Technical concerns NOT addressed in this design.

Rules:
- Return only the SDD in Markdown. No preamble.
- Be specific. Use exact names for tables, routes, fields.
- Do not over-engineer. Prefer simple, mainstream choices.
- Do not include code, only design.
"""

SUMMARIZE_PROMPT = """
Compress the following PRD into a technical brief under 1500 tokens.
Keep: features, users, tech stack mentions, acceptance criteria, constraints.
Remove: prose, repetition, examples, marketing language.
Return only the compressed brief.
"""

@lru_cache(maxsize=1)
def _get_architect_llm():
    """Reuse a single LLM client across compression + generation calls."""
    return get_llm("architect")


async def run_architect_agent(project_slug: str) -> str:
    """Reads PRD, generates SDD, saves it, and returns the saved path."""
    print(f"[Architect Agent] Starting for project: {project_slug}")
    
    # 1. Read the PRD generated by the PM Agent
    try:
        prd = read_project_file(project_slug, "prd.md")
    except FileNotFoundError:
        raise Exception(f"Missing prd.md for '{project_slug}'. Run PM agent first.")
        
    llm = _get_architect_llm()
    print(f"[Architect Agent] Received PRD ({len(prd)} chars)")

    # 2. Compress if needed (Local model token limits)
    if len(prd) > MAX_PRD_CHARS:
        original_len = len(prd)
        print("[Architect Agent] PRD too large — compressing...")
        prd = await llm.complete(
            system=SUMMARIZE_PROMPT,
            user=prd,
            temperature=0.1,
        )
        print(f"[Architect Agent] Compressed {original_len} → {len(prd)} chars")

    # 3. Generate the SDD
    print("[Architect Agent] Calling LLM...")
    sdd = await llm.complete(
        system=ARCHITECT_SYSTEM_PROMPT,
        user=prd,
        temperature=0.2,
    )

    # 4. Save the SDD to disk
    saved_path = save_text(project_slug, "sdd.md", sdd)
    print(f"[Architect Agent] SDD saved to: {saved_path}\n")
    
    # 5. Return the path for LangGraph
    return str(saved_path)


# ── Standalone Entry Point (Kept for manual testing) ──
if __name__ == "__main__":
    from output_store import list_projects
    import sys
    
    projects = list_projects()
    if not projects:
        print("No projects found. Run PM agent first.")
        sys.exit(1)
        
    print("Available Projects:")
    for i, p in enumerate(projects, 1):
        print(f"  {i}. {p}")
        
    try:
        choice = input(f"Pick [default: 1 = {projects[0]}]: ").strip()
        idx = int(choice) - 1 if choice else 0
        slug = projects[idx]
    except (ValueError, IndexError):
        slug = projects[0]

    asyncio.run(run_architect_agent(slug))